CREATE OR REPLACE VIEW customer_order_details AS
SELECT
  o.id AS order_id, o.order_no, o.status, o.subtotal, o.shipping_fee, o.total,
  o.placed_at, o.customer_id, a.full_name, a.phone, a.email, a.street,
  a.barangay, a.city, a.province, a.zip, i.product_id,
  i.name AS product_name, i.colorway, i.size, i.qty, i.unit_price
FROM orders o
JOIN order_addresses a ON a.order_id = o.id
JOIN order_items i ON i.order_id = o.id;

